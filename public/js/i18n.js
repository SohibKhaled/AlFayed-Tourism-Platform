export function t(lang, key) {
  return STRINGS[lang]?.[key] || STRINGS.ar[key] || key;
}

export function formatCurrency(usdAmount, currency = 'EGP', rates = { EGP: 49.5, SAR: 3.75, AED: 3.67, USD: 1 }) {
  const rate = rates[currency] ?? 1;
  const val = Number(usdAmount || 0) * rate;
  const maxFrac = currency === 'USD' ? 2 : 0;
  try {
    return new Intl.NumberFormat('en-US', {
      style: 'currency',
      currency,
      minimumFractionDigits: 0,
      maximumFractionDigits: maxFrac,
    }).format(val);
  } catch {
    return `${Math.round(val)} ${currency}`;
  }
}

export function diffDays(checkIn, checkOut) {
  if (!checkIn || !checkOut) return 2;
  const a = new Date(`${checkIn}T00:00:00Z`).getTime();
  const b = new Date(`${checkOut}T00:00:00Z`).getTime();
  const days = Math.round((b - a) / 86400000);
  return Number.isFinite(days) && days >= 1 ? Math.min(30, days) : 2;
}
